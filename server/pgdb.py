"""ExamFlow AI - Postgres adapter that keeps the SQLite call style.

The application talks to the database through ``sqlite3``-shaped calls
(``conn.execute(sql, params)``, ``conn.commit()``, ``conn.executescript``).
This module implements the same surface on top of a managed Postgres instance so
the business logic does not need to know which engine is behind it.

The SQLite dialect pieces are translated on the way through:

* ``?`` placeholders            -> ``%s``
* ``PRAGMA table_info(t)``      -> ``information_schema.columns`` lookup
* ``PRAGMA foreign_keys = ON``  -> ignored (always on in Postgres)
* ``INSERT OR IGNORE``          -> ``INSERT ... ON CONFLICT DO NOTHING``
* ``INSERT OR REPLACE``         -> ``INSERT ... ON CONFLICT (id) DO UPDATE``
* ``executescript``             -> statement-by-statement execution

Set ``DATABASE_URL`` (or ``EXAMFLOW_PG_URL``) to switch the whole application to
Postgres; without it the app keeps using the SQLite file.
"""
import os
import re
import threading

try:  # pragma: no cover - exercised only when the driver is installed
    import psycopg2
    import psycopg2.extras
    DRIVER_ERROR = None
except Exception as exc:  # pragma: no cover
    psycopg2 = None
    DRIVER_ERROR = exc


def configured_url():
    for name in ("DATABASE_URL", "EXAMFLOW_PG_URL", "POSTGRES_URL", "POSTGRES_PRISMA_URL"):
        value = (os.environ.get(name) or "").strip()
        if value.startswith("postgres://") or value.startswith("postgresql://"):
            # Vercel/Neon hand out "postgres://"; psycopg2 wants a scheme it knows.
            return value.replace("postgres://", "postgresql://", 1)
    return ""


def enabled():
    return bool(configured_url() and psycopg2 is not None)


def _normalise_url(url):
    if "sslmode=" not in url and "localhost" not in url and "127.0.0.1" not in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"
    return url


def translate(sql, params=None):
    """Rewrite a SQLite statement for Postgres."""
    text = sql.strip()

    pragma = re.match(r"^PRAGMA\s+table_info\(\s*[`\"']?(\w+)[`\"']?\s*\)\s*;?$", text, re.I)
    if pragma:
        table = pragma.group(1)
        text = (
            "SELECT column_name AS name, data_type AS type FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = '%s' ORDER BY ordinal_position"
            % table
        )
        return text

    if re.match(r"^PRAGMA\b", text, re.I):
        # PRAGMAs only tune SQLite; Postgres always enforces foreign keys.
        return "SELECT 1 WHERE 1 = 0"

    if re.match(r"^INSERT\s+OR\s+IGNORE\b", text, re.I):
        text = re.sub(r"^INSERT\s+OR\s+IGNORE\b", "INSERT", text, flags=re.I)
        if "on conflict" not in text.lower():
            text = text.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    elif re.match(r"^INSERT\s+OR\s+REPLACE\b", text, re.I):
        text = re.sub(r"^INSERT\s+OR\s+REPLACE\b", "INSERT", text, flags=re.I)
        if "on conflict" not in text.lower():
            text = text.rstrip().rstrip(";") + " ON CONFLICT (id) DO UPDATE SET updated_at = EXCLUDED.updated_at"

    if params is not None and "?" in text:
        text = text.replace("%s", "%%s").replace("?", "%s")

    return text


def split_statements(script):
    statements, buffer = [], []
    in_string = False
    for char in script:
        if char == "'":
            in_string = not in_string
        if char == ";" and not in_string:
            chunk = "".join(buffer).strip()
            if chunk:
                statements.append(chunk)
            buffer = []
            continue
        buffer.append(char)
    tail = "".join(buffer).strip()
    if tail:
        statements.append(tail)
    return statements


class PgCursor:
    """Cursor seam exposing the ``sqlite3``-style helpers the app uses."""

    def __init__(self, cursor):
        self._cursor = cursor
        self._prefetched = None

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def lastrowid(self):  # Postgres ids are generated by the app, never by the DB
        return None

    @property
    def description(self):
        return self._cursor.description

    def fetchone(self):
        if self._prefetched is not None:
            row, self._prefetched = self._prefetched, None
            return row
        return self._cursor.fetchone()

    def fetchall(self):
        rows = self._cursor.fetchall()
        if self._prefetched is not None:
            rows = [self._prefetched] + list(rows)
            self._prefetched = None
        return rows

    def __iter__(self):
        return iter(self.fetchall())


class PgConnection:
    def __init__(self, raw, pool=None):
        self._raw = raw
        self._pool = pool
        self._raw.autocommit = False

    def execute(self, sql, params=None):
        text = translate(sql, params)
        cursor = self._raw.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
        # This schema stores every flag as INTEGER (is_active, is_enabled, is_mandatory,
        # is_read). The UI and the JSON API send real booleans, and Postgres refuses to
        # compare an integer column with a boolean, so normalise here once.
        bound = tuple(int(v) if isinstance(v, bool) else v for v in params) if params else None
        try:
            cursor.execute(text, bound)
        except Exception:
            cursor.close()
            raise
        return PgCursor(cursor)

    def executescript(self, script):
        last = None
        for statement in split_statements(script):
            last = self.execute(statement)
        return last

    def commit(self):
        self._raw.commit()

    def rollback(self):
        try:
            self._raw.rollback()
        except Exception:
            pass

    def close(self):
        if self._pool is not None:
            pool, self._pool = self._pool, None
            try:
                self._raw.rollback()
                healthy = self._raw.closed == 0
            except Exception:
                healthy = False
            try:
                pool.putconn(self._raw, close=not healthy)
            except Exception:
                try:
                    self._raw.close()
                except Exception:
                    pass
            return
        try:
            self._raw.close()
        except Exception:
            pass

    # sqlite3 compatibility shims
    def cursor(self):
        return PgCursor(self._raw.cursor(cursor_factory=psycopg2.extras.RealDictCursor))


_pool = None
_pool_lock = threading.Lock()
POOL_MAX = int(os.environ.get("EXAMFLOW_PG_POOL_MAX") or 8)


def _connection_kwargs():
    return {"connect_timeout": 10, "application_name": "examflow",
            "keepalives": 1, "keepalives_idle": 30, "keepalives_interval": 10,
            "keepalives_count": 3}


def _get_pool():
    """One small warm pool per process.

    A serverless request used to pay a fresh TCP + TLS handshake (and sometimes a
    Neon wake-up) before it could run a single query; reusing pooled connections
    removes that cost from every request after the first.
    """
    global _pool
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                from psycopg2 import pool as pgpool
                url = _normalise_url(configured_url())
                _pool = pgpool.ThreadedConnectionPool(1, POOL_MAX, url, **_connection_kwargs())
    return _pool


def connect():
    if psycopg2 is None:  # pragma: no cover
        raise RuntimeError("psycopg2 is not installed: %s" % DRIVER_ERROR)
    global _pool
    try:
        pool = _get_pool()
        raw = pool.getconn()
        return PgConnection(raw, pool=pool)
    except Exception:
        # A stale pool (database restarted, credentials rotated) must not break the
        # request: drop it and fall back to a direct connection.
        with _pool_lock:
            stale, _pool = _pool, None
        if stale is not None:
            try:
                stale.closeall()
            except Exception:
                pass
        url = _normalise_url(configured_url())
        conn = psycopg2.connect(url, **_connection_kwargs())
        return PgConnection(conn)
